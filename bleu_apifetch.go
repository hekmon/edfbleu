package main

import (
	"encoding/json"
	"fmt"
	"net/http"
	"time"
)

const (
	tempoAPIURL        = "https://www.api-couleur-tempo.fr/api/joursTempo"
	tempoAPIJourFormat = "2006-01-02" // dateJour format of the API
	// codeJour values as served by the API (correspondance with libCouleur verified on the live payload):
	// 1 = Bleu, 2 = Blanc, 3 = Rouge, 0 = undecided (libCouleur "Inconnu")
	tempoAPIJourWhite = 2
	tempoAPIJourRed   = 3
)

var (
	// usingAPIData is true when the tempo day lists come from the runtime API fetch
	usingAPIData bool
	// apiLastDecided is the date of the last decided tempo day when usingAPIData is true
	apiLastDecided time.Time
)

// tempoAPIDay is a single entry of the joursTempo payload
type tempoAPIDay struct {
	DateJour   string `json:"dateJour"`
	CodeJour   int    `json:"codeJour"`
	LibCouleur string `json:"libCouleur"`
}

// updateTempoDaysFromAPI tries to replace the compiled tempo calendar with up to
// date data fetched from api-couleur-tempo.fr (a free third-party API serving the
// RTE Tempo data) using a single GET. On any failure (network error, non 200,
// invalid or empty payload) the compiled calendar generated by generateTempoDays()
// is kept untouched and a warning is printed: this fetch must never make the
// program crash.
func updateTempoDaysFromAPI() {
	// Fetch (one single GET with a reasonable timeout)
	client := &http.Client{Timeout: 10 * time.Second}
	resp, err := client.Get(tempoAPIURL)
	if err != nil {
		fallbackToCompiledTempoDays(err)
		return
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		fallbackToCompiledTempoDays(fmt.Errorf("unexpected HTTP status %q", resp.Status))
		return
	}
	var days []tempoAPIDay
	if err := json.NewDecoder(resp.Body).Decode(&days); err != nil {
		fallbackToCompiledTempoDays(fmt.Errorf("invalid JSON payload: %w", err))
		return
	}
	if len(days) == 0 {
		fallbackToCompiledTempoDays(fmt.Errorf("empty payload"))
		return
	}
	// Rebuild the day lists, skipping undecided days (no color yet: can not be priced)
	var (
		apiRedDays   []time.Time
		apiWhiteDays []time.Time
		lastDecided  time.Time
	)
	for _, day := range days {
		if day.CodeJour == 0 || day.LibCouleur == "Inconnu" {
			continue
		}
		date, err := time.ParseInLocation(tempoAPIJourFormat, day.DateJour, frLocation)
		if err != nil {
			fallbackToCompiledTempoDays(fmt.Errorf("invalid date %q: %w", day.DateJour, err))
			return
		}
		switch day.CodeJour {
		case tempoAPIJourRed:
			apiRedDays = append(apiRedDays, date)
		case tempoAPIJourWhite:
			apiWhiteDays = append(apiWhiteDays, date)
		}
		if date.After(lastDecided) {
			lastDecided = date
		}
	}
	if lastDecided.IsZero() {
		fallbackToCompiledTempoDays(fmt.Errorf("no decided day in payload"))
		return
	}
	// Success: replace the compiled calendar
	redDays = apiRedDays
	whiteDays = apiWhiteDays
	apiLastDecided = lastDecided
	usingAPIData = true
}

// fallbackToCompiledTempoDays warns the user that the API fetch failed and that
// the program keeps using the internal (compiled) tempo data
func fallbackToCompiledTempoDays(err error) {
	fmt.Println()
	fmt.Printf("/!\\ failed to fetch the tempo days calendar from the API: %v\n", err)
	fmt.Printf("/!\\ using the internal tempo data instead (last update: %s)\n", lastDataUpdate)
	fmt.Println()
}
